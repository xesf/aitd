#!/usr/bin/env python3
"""
extract_tables.py - pull the constant tables the renderer needs out of
WAITD3.EXE and write them as C arrays to src/exe_tables.c.

    python3 tools/extract_tables.py ida/WAITD3.EXE src/exe_tables.c

The tables are not closed-form (the sine table, for instance, has sin(0) = 4),
so they are copied byte for byte instead of being recomputed.
"""

import struct
import sys

# (C name, virtual address, element format, element count, comment)
TABLES = [
    ("g_sin_table", 0x439abc, "h", 1024,
     "0x439abc - 1024 entry sine table, 0x7fff = 1.0; cos(a) = sin(a + 256)"),
    ("g_poly_noise", 0x401000, "B", 0x10800,
     "0x401000..0x411800 - code bytes the dithered fill (0x402246) reads as "
     "noise, starting at 0x401acc; index 0xacc is 0x401acc"),
    ("g_poly_ramp", 0x42f988, "B", 16 * 321,
     "0x42f988 - per-width run lengths for the horizontal ramp fills"),
]


def load_sections(exe):
    pe = struct.unpack_from("<I", exe, 0x3C)[0]
    count = struct.unpack_from("<H", exe, pe + 6)[0]
    opt = struct.unpack_from("<H", exe, pe + 20)[0]
    sections = []
    for i in range(count):
        off = pe + 24 + opt + 40 * i
        _vsize, va, rsize, raw = struct.unpack_from("<IIII", exe, off + 8)
        sections.append((0x400000 + va, rsize, raw))
    return sections


def read(exe, sections, va, size):
    for base, rsize, raw in sections:
        if base <= va and va + size <= base + rsize:
            return exe[raw + va - base: raw + va - base + size]
    # .bss and friends have no file backing: zero filled.
    return bytes(size)


def main():
    exe = open(sys.argv[1], "rb").read()
    sections = load_sections(exe)
    out = ["/*", " * exe_tables.c - generated by tools/extract_tables.py from WAITD3.EXE.",
           " * Do not edit by hand.", " */", "", '#include "exe_tables.h"', ""]
    for name, va, fmt, count, comment in TABLES:
        size = struct.calcsize("<" + fmt) * count
        values = struct.unpack("<%d%s" % (count, fmt), read(exe, sections, va, size))
        ctype = {"h": "const s16", "B": "const u8"}[fmt]
        out.append("/* %s */" % comment)
        out.append("%s %s[%d] = {" % (ctype, name, count))
        for i in range(0, count, 16):
            out.append("    " + ", ".join(str(v) for v in values[i:i + 16]) + ",")
        out.append("};")
        out.append("")
    open(sys.argv[2], "w").write("\n".join(out))


if __name__ == "__main__":
    main()
